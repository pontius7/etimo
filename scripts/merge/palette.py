#!/usr/bin/env python3
"""Family colours for the 4 Devter families, chosen and validated against Etimo's 5.

Run:  python3 scripts/merge/palette.py            -> prints the validation table
      python3 scripts/merge/palette.py --search   -> re-runs the search that produced FAM below

Rules (from the merge brief):
  * Etimo's 5 family colours never change.
  * All 9 families pairwise CIEDE2000 >= 20 in each theme (target; Etimo-Etimo pairs reported as-is).
  * New colours reach >= 3:1 contrast against --land and --bg (map marks).
  * Same tonal style as Etimo: OKLCH lightness/chroma in Etimo's range; each new family gets a hue
    window that Etimo's per-language bands do not use, so per-language shades stay separable.
The per-language map `P` (inline script) for Devter languages is generated by `language_shades()`
in the same way Etimo's is laid out: hue walks across the family band in tree order while
lightness cycles through Etimo's levels.
"""
import math, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import families  # noqa: E402

BG = {'light': {'bg': '#f8f8f6', 'land': '#fbfaf6'}, 'dark': {'bg': '#080f0d', 'land': '#0d221d'}}
ETIMO = {
    'light': {'Slavic': '#21843c', 'Iranian': '#bd871c', 'Albanian': '#8f141e', 'Greek': '#1351a6', 'Romance': '#9860d0'},
    'dark': {'Slavic': '#7ad689', 'Iranian': '#ebb353', 'Albanian': '#ffa09a', 'Greek': '#95c0ff', 'Romance': '#d0a9ff'},
}
VAR = {'Slavic': 'slav', 'Iranian': 'iran', 'Albanian': 'alba', 'Greek': 'gree', 'Romance': 'roma',
       'Caucasian': 'cauc', 'Turkic': 'turk', 'Uralic': 'ural', 'Mongolic': 'mong'}
# Chosen with --search (hue windows below) then hand-tuned in OKLCH; kept literal so builds are reproducible.
FAM = {
    'light': {'Caucasian': '#d05418', 'Turkic': '#5b5500', 'Uralic': '#06899d', 'Mongolic': '#8b186c'},
    'dark': {'Caucasian': '#ea702c', 'Turkic': '#e1f15d', 'Uralic': '#44d4e2', 'Mongolic': '#d553ac'},
}
for _n, _d in families.EXTRA.items():   # families added in content/families.json
    VAR[_n] = _d['key']
    FAM['light'][_n], FAM['dark'][_n] = _d['light'], _d['dark']
# hue windows (OKLCH degrees) for the per-language bands; chosen next to gaps in Etimo's bands
WINDOWS = {'Caucasian': (40, 56), 'Turkic': (100, 128), 'Uralic': (212, 240), 'Mongolic': (330, 354)}


# ---------------------------------------------------------------- colour maths
def hex2rgb(h):
    h = h.lstrip('#')
    return [int(h[i:i + 2], 16) / 255 for i in (0, 2, 4)]


def rgb2hex(c):
    return '#' + ''.join(f'{max(0, min(255, round(v * 255))):02x}' for v in c)


def lin(v):
    return v / 12.92 if v <= .04045 else ((v + .055) / 1.055) ** 2.4


def delin(v):
    return 12.92 * v if v <= .0031308 else 1.055 * v ** (1 / 2.4) - .055


def oklch2rgb(L, C, H):
    a, b = C * math.cos(math.radians(H)), C * math.sin(math.radians(H))
    l_ = (L + .3963377774 * a + .2158037573 * b) ** 3
    m_ = (L - .1055613458 * a - .0638541728 * b) ** 3
    s_ = (L - .0894841775 * a - 1.2914855480 * b) ** 3
    r = 4.0767416621 * l_ - 3.3077115913 * m_ + .2309699292 * s_
    g = -1.2684380046 * l_ + 2.6097574011 * m_ - .3413193965 * s_
    bb = -.0041960863 * l_ - .7034186147 * m_ + 1.7076147010 * s_
    rgb = [r, g, bb]
    ok = all(-1e-4 <= v <= 1 + 1e-4 for v in rgb)
    return [delin(max(0, min(1, v))) for v in rgb], ok


def rgb2oklch(rgb):
    r, g, b = [lin(v) for v in rgb]
    l = (.4122214708 * r + .5363325363 * g + .0514459929 * b) ** (1 / 3)
    m = (.2119034982 * r + .6806995451 * g + .1073969566 * b) ** (1 / 3)
    s = (.0883024619 * r + .2817188376 * g + .6299787005 * b) ** (1 / 3)
    L = .2104542553 * l + .7936177850 * m - .0040720468 * s
    a = 1.9779984951 * l - 2.4285922050 * m + .4505937099 * s
    bb = .0259040371 * l + .7827717662 * m - .8086757660 * s
    return L, math.hypot(a, bb), math.degrees(math.atan2(bb, a)) % 360


def rgb2lab(rgb):
    r, g, b = [lin(v) for v in rgb]
    x = (.4124564 * r + .3575761 * g + .1804375 * b) / .95047
    y = (.2126729 * r + .7151522 * g + .0721750 * b)
    z = (.0193339 * r + .1191920 * g + .9503041 * b) / 1.08883
    f = lambda t: t ** (1 / 3) if t > 216 / 24389 else (24389 / 27 * t + 16) / 116
    fx, fy, fz = f(x), f(y), f(z)
    return 116 * fy - 16, 500 * (fx - fy), 200 * (fy - fz)


def ciede2000(c1, c2):
    L1, a1, b1 = rgb2lab(hex2rgb(c1))
    L2, a2, b2 = rgb2lab(hex2rgb(c2))
    C1, C2 = math.hypot(a1, b1), math.hypot(a2, b2)
    Cb = (C1 + C2) / 2
    G = .5 * (1 - math.sqrt(Cb ** 7 / (Cb ** 7 + 25 ** 7)))
    a1p, a2p = (1 + G) * a1, (1 + G) * a2
    C1p, C2p = math.hypot(a1p, b1), math.hypot(a2p, b2)
    h1p = math.degrees(math.atan2(b1, a1p)) % 360
    h2p = math.degrees(math.atan2(b2, a2p)) % 360
    dLp, dCp = L2 - L1, C2p - C1p
    dhp = 0 if C1p * C2p == 0 else (h2p - h1p if abs(h2p - h1p) <= 180 else (h2p - h1p - 360 if h2p > h1p else h2p - h1p + 360))
    dHp = 2 * math.sqrt(C1p * C2p) * math.sin(math.radians(dhp / 2))
    Lbp, Cbp = (L1 + L2) / 2, (C1p + C2p) / 2
    if C1p * C2p == 0:
        hbp = h1p + h2p
    elif abs(h1p - h2p) <= 180:
        hbp = (h1p + h2p) / 2
    else:
        hbp = (h1p + h2p + 360) / 2 if h1p + h2p < 360 else (h1p + h2p - 360) / 2
    T = (1 - .17 * math.cos(math.radians(hbp - 30)) + .24 * math.cos(math.radians(2 * hbp))
         + .32 * math.cos(math.radians(3 * hbp + 6)) - .20 * math.cos(math.radians(4 * hbp - 63)))
    dth = 30 * math.exp(-((hbp - 275) / 25) ** 2)
    Rc = 2 * math.sqrt(Cbp ** 7 / (Cbp ** 7 + 25 ** 7))
    Sl = 1 + .015 * (Lbp - 50) ** 2 / math.sqrt(20 + (Lbp - 50) ** 2)
    Sc, Sh = 1 + .045 * Cbp, 1 + .015 * Cbp * T
    Rt = -math.sin(math.radians(2 * dth)) * Rc
    return math.sqrt((dLp / Sl) ** 2 + (dCp / Sc) ** 2 + (dHp / Sh) ** 2 + Rt * (dCp / Sc) * (dHp / Sh))


def contrast(c1, c2):
    y = lambda c: sum(k * lin(v) for k, v in zip((.2126, .7152, .0722), hex2rgb(c)))
    a, b = sorted((y(c1), y(c2)), reverse=True)
    return (a + .05) / (b + .05)


# ---------------------------------------------------------------- validation
def table(theme, fam=None):
    allc = dict(ETIMO[theme], **(fam or FAM[theme]))
    names = list(allc)
    rows, worst_new, worst_all = [], 99, 99
    for i, a in enumerate(names):
        for b in names[i + 1:]:
            d = ciede2000(allc[a], allc[b])
            new = a in FAM[theme] or b in FAM[theme]
            rows.append((a, b, d, new))
            worst_all = min(worst_all, d)
            if new:
                worst_new = min(worst_new, d)
    con = {n: (contrast(c, BG[theme]['land']), contrast(c, BG[theme]['bg'])) for n, c in allc.items()}
    return rows, worst_new, worst_all, con


def report():
    out = []
    ok = True
    for theme in ('light', 'dark'):
        rows, wn, wa, con = table(theme)
        out.append(f'## {theme} theme')
        out.append('| family | colour | OKLCH L/C/H | contrast vs --land | vs --bg |')
        out.append('|---|---|---|---|---|')
        for n, c in dict(ETIMO[theme], **FAM[theme]).items():
            L, C, H = rgb2oklch(hex2rgb(c))
            tag = '' if n in ETIMO[theme] else ' (new)'
            out.append(f'| {n}{tag} | `{c}` | {L:.2f} / {C:.3f} / {H:.0f} | {con[n][0]:.2f}:1 | {con[n][1]:.2f}:1 |')
            if n in FAM[theme] and min(con[n]) < 3:
                ok = False
        out.append('')
        out.append(f'min CIEDE2000 for pairs involving a new family: **{wn:.1f}**; over all 36 pairs: {wa:.1f}')
        low = [r for r in rows if r[2] < 20]
        if low:
            out.append('pairs under 20: ' + ', '.join(f'{a}/{b} {d:.1f}{"" if n else " (Etimo-Etimo, unchanged)"}' for a, b, d, n in low))
        if wn < 20:
            ok = False
        out.append('')
    return '\n'.join(out), ok


# ---------------------------------------------------------------- search
def search():
    best = {}
    for theme, (Lr, Cr) in {'light': ((.44, .62), (.10, .17)), 'dark': ((.74, .88), (.09, .15))}.items():
        cands = {}
        for fam, (h0, h1) in WINDOWS.items():
            cs = []
            for H in range(h0, h1 + 1, 2):
                for Li in range(int(Lr[0] * 100), int(Lr[1] * 100) + 1, 2):
                    for Ci in range(int(Cr[0] * 100), int(Cr[1] * 100) + 1, 1):
                        rgb, ok = oklch2rgb(Li / 100, Ci / 100, H)
                        if not ok:
                            continue
                        hx = rgb2hex(rgb)
                        if min(contrast(hx, BG[theme]['land']), contrast(hx, BG[theme]['bg'])) < 3.05:
                            continue
                        dmin = min(ciede2000(hx, e) for e in ETIMO[theme].values())
                        cs.append((dmin, hx))
            cs.sort(reverse=True)
            cands[fam] = [c for c in cs[:60]]
        # pick the combination maximising the minimum pairwise distance
        import itertools
        top = None
        fams = list(WINDOWS)
        for combo in itertools.product(*[cands[f][:25] for f in fams]):
            m = min(c[0] for c in combo)
            for i in range(4):
                for j in range(i + 1, 4):
                    m = min(m, ciede2000(combo[i][1], combo[j][1]))
            if top is None or m > top[0]:
                top = (m, {f: c[1] for f, c in zip(fams, combo)})
        best[theme] = top
        print(theme, round(top[0], 1), top[1])
    return best


# ---------------------------------------------------------------- per-language shades
LEVELS = [.79, .55, .70, .44, .62, .40, .74, .50]


def language_shades(fam, langs):
    """langs: language names in tree order. Returns {name: hex} in Etimo's per-language style."""
    h0, h1 = WINDOWS[fam]
    h0, h1 = h0 - 6, h1 + 6  # Etimo's own bands are ~35-80 degrees wide
    base = rgb2oklch(hex2rgb(FAM['light'][fam]))
    out = {}
    n = len(langs)
    for i, name in enumerate(langs):
        H = h0 + (h1 - h0) * (i / max(1, n - 1))
        L = LEVELS[i % len(LEVELS)]
        C = min(.17, base[1] + .02)
        while True:
            rgb, ok = oklch2rgb(L, C, H)
            if ok or C < .05:
                break
            C -= .005
        out[name] = rgb2hex(rgb)
    return out


if __name__ == '__main__':
    if '--search' in sys.argv:
        search()
    else:
        txt, ok = report()
        print(txt)
        print('PASS' if ok else 'FAIL')
        sys.exit(0 if ok else 1)
